def rows(template, facts, route):
    result = []
    for definition, (status, fact, evidence, reason, next_step) in zip(template, facts, strict=True):
        ident, claim, requirement, basis, url, examples = definition
        result.append({"rule_id": ident, "claim": claim, "requirement": requirement, "basis": basis,
                       "source_url": url, "examples": examples, "route": route,
                       "layer": "模型设计/产品约定" if ident == "J04" else "地方参考规则" if route == "transition" else "政策条件",
                       "status": status, "fact": fact, "evidence": evidence, "reason": reason,
                       "next_evidence": next_step, "task_scope": "current"})
    return result


